#!/usr/bin/env node
// scripts/generate-thumbnail-map.js
//
// Scans public/html/<slug>/ and writes data/thumbnails.generated.js, an
// auto-built map of slug -> thumbnail path. data/games.js consults this
// map so games no longer need a manual `thumbnail:` override when their
// art file isn't named thumb.png.
//
// Wired into npm run dev / build via "gen:thumbnails".

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const HTML_DIR = path.join(ROOT, 'public', 'html');
const OUT_FILE = path.join(ROOT, 'data', 'thumbnails.generated.js');

const IMAGE_EXTS = ['.png', '.jpg', '.jpeg', '.webp'];
const THUMB_PRIORITY = ['thumb.png', 'thumb.jpg', 'thumb.jpeg', 'thumb.webp'];

function pickThumbnail(slugDir) {
  let entries;
  try {
    entries = fs.readdirSync(slugDir, { withFileTypes: true });
  } catch {
    return null;
  }
  const fileNames = entries.filter((e) => e.isFile()).map((e) => e.name);

  for (const candidate of THUMB_PRIORITY) {
    const hit = fileNames.find((n) => n.toLowerCase() === candidate);
    if (hit) return hit;
  }

  const images = fileNames
    .filter((n) => IMAGE_EXTS.includes(path.extname(n).toLowerCase()))
    .sort((a, b) => a.localeCompare(b));
  return images[0] || null;
}

function build() {
  const map = {};
  const dirs = fs
    .readdirSync(HTML_DIR, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  for (const slug of dirs) {
    const file = pickThumbnail(path.join(HTML_DIR, slug));
    if (file) map[slug] = `/html/${slug}/${file}`;
  }
  return map;
}

function render(map) {
  const lines = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slug, file]) => `  '${slug}': '${file}',`);
  return [
    '// AUTO-GENERATED by scripts/generate-thumbnail-map.js. Do not edit by hand.',
    '// Run `npm run gen:thumbnails` to refresh.',
    '',
    'const thumbnails = {',
    ...lines,
    '};',
    '',
    'export default thumbnails;',
    '',
  ].join('\n');
}

const map = build();
fs.writeFileSync(OUT_FILE, render(map), 'utf8');
console.log(`thumbnails: wrote ${Object.keys(map).length} entries -> ${path.relative(ROOT, OUT_FILE)}`);
